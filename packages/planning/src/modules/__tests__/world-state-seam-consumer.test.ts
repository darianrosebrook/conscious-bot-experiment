/**
 * Consumer-side /state seam contract (Phase 3 contract layer).
 *
 * Planning consumes minecraft-interface's GET /state and unwraps
 * `data.worldState.environment.nearbyBlocks`, indexing `.position` per block
 * (see task-integration verifyNearbyBlock). When that shape drifted to a
 * string name list, the type definitions still looked fine and the crash
 * surfaced here at runtime. This test validates the *captured producer
 * payload* — the same committed fixture the producer's own seam tests
 * generate from its builder — against the shared schema in
 * executor-contracts, so producer drift fails a planning test too.
 */

import { describe, it, expect } from 'vitest';
import { readFileSync } from 'node:fs';
import { join } from 'node:path';
import {
  WorldStateEnvelopeSchema,
  FullWorldStateSchema,
} from '@conscious-bot/executor-contracts';

// Committed artifact generated by the producer's builder
// (minecraft-interface/src/world-state-response.ts) — cross-package fixture,
// read as data, not imported as code.
const FIXTURE_PATH = join(
  __dirname,
  '../../../../minecraft-interface/src/__tests__/fixtures/world-state-full-captured.json'
);

const DRIFTED_FIXTURE_PATH = join(
  __dirname,
  '../../../../minecraft-interface/src/__tests__/fixtures/world-state-drifted-legacy.json'
);

describe('/state seam from the consumer side', () => {
  it('captured producer payload validates against the shared schema', () => {
    const envelope = JSON.parse(readFileSync(FIXTURE_PATH, 'utf8'));
    const parsed = WorldStateEnvelopeSchema.safeParse(envelope);
    expect(parsed.success).toBe(true);
  });

  it("the consumer's unwrap path yields positioned blocks", () => {
    const envelope = JSON.parse(readFileSync(FIXTURE_PATH, 'utf8'));
    const blocks =
      // Same unwrap chain as task-integration verifyNearbyBlock:
      // res.json() -> data -> worldState -> environment -> nearbyBlocks
      (envelope as any)?.data?.worldState?.environment?.nearbyBlocks;
    expect(Array.isArray(blocks)).toBe(true);
    expect(blocks.length).toBeGreaterThan(0);
    for (const block of blocks) {
      expect(block.position).toEqual(
        expect.objectContaining({
          x: expect.any(Number),
          y: expect.any(Number),
          z: expect.any(Number),
        })
      );
    }
  });

  it('the pre-fix drifted payload fails the schema its consumer depended on', () => {
    const drifted = JSON.parse(readFileSync(DRIFTED_FIXTURE_PATH, 'utf8'));
    expect(WorldStateEnvelopeSchema.safeParse(drifted).success).toBe(false);
    const wsParsed = FullWorldStateSchema.safeParse(drifted?.data?.worldState);
    expect(wsParsed.success).toBe(false);
    // The unwrap path that crashed planning returns undefined on it.
    expect(drifted?.data?.worldState?.environment?.nearbyBlocks).toBeUndefined();
  });
});
